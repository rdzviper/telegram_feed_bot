async def main():
    print(f"model={config.DEEPSEEK_MODEL}\n")
    misses = 0
    for name, expected, text in CASES:
        r = await analyzer.analyze(text)
        got = r["is_ad"]
        ok = got == expected
        misses += not ok
        print(f"{'OK ' if ok else '!! '}{name}: ожид is_ad={expected} факт={got}")
        if not ok:
            print(f"     summary: {r['summary']!r}")
    print(f"\n{len(CASES) - misses}/{len(CASES)} совпало с ожиданием")


if __name__ == "__main__":
    asyncio.run(main())
