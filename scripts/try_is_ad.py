async def one(prompt: str, text: str) -> dict:
    n = target_concept_count(text)
    r = await _client.chat.completions.create(
        messages=[{"role": "user", "content": prompt.format(text=text[:1500], n=n)}],
        model=config.DEEPSEEK_MODEL, temperature=0,
        response_format={"type": "json_object"},
        extra_body={"thinking": {"type": "disabled"}}, max_tokens=250,
    )
    try:
        return json.loads(r.choices[0].message.content or "{}")
    except Exception:
        return {"is_ad": "PARSE_ERR"}


async def main():
    print(f"model={config.DEEPSEEK_MODEL}\n")
    for name, expected, text in CASES:
        old, new = await asyncio.gather(one(_ANALYZE_PROMPT, text), one(_NEW_PROMPT, text))
        o, n = old.get("is_ad"), new.get("is_ad")
        mark = "OK " if n == expected else "!! "
        print(f"{mark}{name}: ожид is_ad={expected} | старый={o} -> новый={n}")
        if n != expected:
            print(f"     summary(new): {new.get('summary')!r}")
    print("\n(OK = новый промт совпал с ожиданием; !! = промах)")


if __name__ == "__main__":
    asyncio.run(main())
